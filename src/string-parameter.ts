import { ContextProvider, RemovalPolicy, Stack, TagManager, TagType, Token, Tokenization } from "aws-cdk-lib";
import * as iam from "aws-cdk-lib/aws-iam";
import * as ssm from "aws-cdk-lib/aws-ssm";
import { IStringParameter } from "aws-cdk-lib/aws-ssm";
import * as cxschema from "aws-cdk-lib/cloud-assembly-schema";
import * as custom_resources from "aws-cdk-lib/custom-resources";
import { Construct } from "constructs";
import { ParameterBase, ParameterOptions } from "./parameter-base";
import { Validators } from "./validators";

/**
 * Properties needed to create a String SSM parameter.
 */
export interface StringParameterProps extends ParameterOptions {
  /**
   * The name of the parameter.
   *
   * It may not be a
   *
   * @default - a name will be generated by CloudFormation
   * @stability stable
   */
  readonly parameterName: string;

  /**
   * The region to create the parameter in. See AWS.SSM.region for more information.
   */
  readonly region: string;

  /**
   * The value of the parameter.
   *
   * It may not reference another parameter and ``{{}}`` cannot be used in the value.
   */
  readonly stringValue: string;

  /**
   * The data type of the parameter, such as `text` or `aws:ec2:image`.
   *
   * @default - undefined
   */
  readonly dataType?: ssm.ParameterDataType;

  /**
   * Whether to retain or delete the parameter on CloudFormation delete event.
   *
   * @default - DESTROY
   */
  readonly removalPolicy?: RemovalPolicy;
}

export interface StringParameterAttributes extends ssm.StringParameterAttributes {
  /**
   * The region to retrieve the parameter from. See AWS.SSM.region for more information.
   */
  readonly region: string;
}

const RESOURCE_TYPE = "Custom::SSM_String_Parameter_Cross_Region";

export class StringParameter extends ParameterBase implements ssm.IStringParameter {
  /**
   * Imports an external string parameter with name and optional version.
   */
  public static fromStringParameterAttributes(
    scope: Construct,
    id: string,
    attrs: StringParameterAttributes
  ): ssm.IStringParameter {
    if (!attrs.parameterName) {
      throw new Error("parameterName cannot be an empty string");
    }

    const parameterType = attrs.type ?? ssm.ParameterType.STRING;

    const parameterName = attrs.version
      ? `${attrs.parameterName}:${Tokenization.stringifyNumber(attrs.version)}`
      : attrs.parameterName;

    return importStringParameter(scope, id, {
      region: attrs.region,
      name: parameterName,
      parameterArn: Stack.of(scope).formatArn({
        service: "ssm",
        resource: `parameter${parameterName}`,
        region: attrs.region,
      }),
      parameterName: attrs.parameterName,
      parameterType: parameterType,
    });
  }

  /**
   * Imports an external string parameter by name and region.
   */
  public static fromStringParameterName(
    scope: Construct,
    id: string,
    region: string,
    parameterName: string
  ): IStringParameter {
    return this.fromStringParameterAttributes(scope, id, { parameterName: parameterName, region: region });
  }

  /**
   * Imports an external string parameter by ARN, e.g. from another account.
   *
   * Only the partition and account of the ARN may be tokens.
   */
  public static fromStringParameterArn(scope: Construct, id: string, parameterArn: string): IStringParameter {
    // arn:partition:ssm:region:account:parameter/name, the partition and account may be tokens
    const [, , service, region, , resource = ""] = parameterArn.split(":");
    if (Token.isUnresolved(region ?? parameterArn) || Token.isUnresolved(resource)) {
      throw new Error("parameterArn must not be a token, except for partition and account");
    }
    const [resourceType, ...resourceName] = resource.split("/");
    if (service !== "ssm" || resourceType !== "parameter" || !region || !resourceName.length) {
      throw new Error(`Invalid SSM parameter ARN: ${parameterArn}`);
    }

    return importStringParameter(scope, id, {
      region: region,
      name: parameterArn,
      parameterArn: parameterArn,
      parameterName: resourceName.length > 1 ? `/${resourceName.join("/")}` : resourceName[0],
      parameterType: ssm.ParameterType.STRING,
    });
  }

  /**
   * Reads the value of an SSM parameter during synthesis through an
   * environmental context provider.
   *
   * Requires that the stack this scope is defined in will have explicit
   * account information. Otherwise, it will fail during synthesis.
   */
  public static valueFromLookup(scope: Construct, region: string, parameterName: string): string {
    return ContextProvider.getValue(scope, {
      provider: cxschema.ContextProvider.SSM_PARAMETER_PROVIDER,
      props: { parameterName: parameterName, region: region },
      dummyValue: `dummy-value-for-${parameterName}`,
    }).value;
  }

  public readonly parameterArn: string;
  public readonly parameterName: string;
  public readonly parameterType: string;
  public readonly stringValue: string;

  readonly tags = new TagManager(TagType.KEY_VALUE, RESOURCE_TYPE);

  constructor(scope: Construct, id: string, props: StringParameterProps) {
    super(scope, id, {
      physicalName: props.parameterName,
    });

    if (props.allowedPattern) {
      Validators.parameterValue(props.stringValue, props.allowedPattern);
    }
    Validators.parameterName(props.parameterName);
    Validators.description(props.description);

    this.parameterArn = Stack.of(this).formatArn({
      service: "ssm",
      resource: `parameter${props.parameterName}`,
      region: props.region,
    });

    const removalPolicy = props.removalPolicy ?? RemovalPolicy.DESTROY;

    const resource = new custom_resources.AwsCustomResource(this, "Resource", {
      resourceType: RESOURCE_TYPE,
      onCreate: {
        region: props.region,
        service: "SSM",
        action: "putParameter", // https://docs.aws.amazon.com/AWSJavaScriptSDK/latest/AWS/SSM.html#putParameter-property
        parameters: {
          Name: props.parameterName,
          Value: props.stringValue,
          AllowedPattern: props.allowedPattern,
          DataType: props.dataType,
          Description: props.description,
          Tags: this.tags.renderedTags,
          Tier: props.tier,
          Type: ssm.ParameterType.STRING,
        },
        physicalResourceId: custom_resources.PhysicalResourceId.of(this.parameterArn),
      },
      onUpdate: {
        region: props.region,
        service: "SSM",
        action: "putParameter", // https://docs.aws.amazon.com/AWSJavaScriptSDK/latest/AWS/SSM.html#putParameter-property
        parameters: {
          Name: props.parameterName,
          Value: props.stringValue,
          AllowedPattern: props.allowedPattern,
          DataType: props.dataType,
          Description: props.description,
          Tags: this.tags.renderedTags,
          Tier: props.tier,
          Type: ssm.ParameterType.STRING,
          Overwrite: true,
        },
        physicalResourceId: custom_resources.PhysicalResourceId.of(this.parameterArn),
      },
      onDelete:
        removalPolicy != RemovalPolicy.RETAIN
          ? {
              region: props.region,
              service: "SSM",
              action: "deleteParameter", // https://docs.aws.amazon.com/AWSJavaScriptSDK/latest/AWS/SSM.html#deleteParameter-property
              parameters: {
                Name: props.parameterName,
              },
              physicalResourceId: custom_resources.PhysicalResourceId.of(this.parameterArn),
            }
          : undefined,
      policy: custom_resources.AwsCustomResourcePolicy.fromSdkCalls({
        resources: custom_resources.AwsCustomResourcePolicy.ANY_RESOURCE,
      }),
    });

    resource.grantPrincipal.addToPrincipalPolicy(
      new iam.PolicyStatement({
        actions: ["ssm:AddTagsToResource"],
        resources: [this.parameterArn],
      })
    );

    this.parameterName = props.parameterName;
    this.parameterType = ssm.ParameterType.STRING;
    this.stringValue = props.stringValue;
  }
}

interface ImportStringParameterOptions {
  readonly region: string;
  /** The name or ARN passed to ssm:GetParameter */
  readonly name: string;
  readonly parameterArn: string;
  readonly parameterName: string;
  readonly parameterType: ssm.ParameterType;
}

function importStringParameter(
  scope: Construct,
  id: string,
  options: ImportStringParameterOptions
): ssm.IStringParameter {
  const getParameter: custom_resources.AwsSdkCall = {
    region: options.region,
    service: "SSM",
    action: "getParameter", // https://docs.aws.amazon.com/AWSJavaScriptSDK/latest/AWS/SSM.html#getParameter-property
    parameters: {
      Name: options.name,
    },
    physicalResourceId: custom_resources.PhysicalResourceId.of(options.parameterArn),
  };

  class Import extends ParameterBase {
    public readonly parameterName = options.parameterName;
    public readonly parameterArn = options.parameterArn;
    public readonly parameterType = options.parameterType;
    public readonly stringValue: string;

    constructor() {
      super(scope, id);

      const parameter = new custom_resources.AwsCustomResource(this, "Resource", {
        resourceType: RESOURCE_TYPE,
        onCreate: getParameter,
        onUpdate: getParameter,
        policy: custom_resources.AwsCustomResourcePolicy.fromSdkCalls({
          resources: custom_resources.AwsCustomResourcePolicy.ANY_RESOURCE,
        }),
      });

      this.stringValue = parameter.getResponseField("Parameter.Value");
    }
  }

  return new Import();
}
